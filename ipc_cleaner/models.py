"""
Data models for IPC (Inter-Process Communication) Cleaner Agent.
Represents System V IPC resources, process metadata, audit reports, and purge results.
"""

from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class ResourceType(str, Enum):
    SHM = "shm"
    MSG = "msg"
    SEM = "sem"
    ALL = "all"


class LeakConfidence(str, Enum):
    HIGH = "HIGH"        # nattch == 0 and creator/last PID dead, or marked 'dest'
    MEDIUM = "MEDIUM"    # nattch == 0, creator alive but zero attaches and stale
    LOW = "LOW"          # zero attaches but recently touched or system service
    NONE = "NONE"        # actively attached (nattch > 0)


def format_bytes_human(num_bytes: int) -> str:
    """Format bytes into human-readable string (B, KB, MB, GB)."""
    if num_bytes < 1024:
        return f"{num_bytes} B"
    for unit in ["KB", "MB", "GB", "TB"]:
        num_bytes /= 1024.0
        if num_bytes < 1024.0:
            return f"{num_bytes:.2f} {unit}"
    return f"{num_bytes:.2f} PB"


class ProcessInfo(BaseModel):
    """Metadata regarding a creator or operator PID associated with IPC."""
    pid: int
    exists: bool = False
    is_zombie: bool = False
    name: Optional[str] = None
    cmdline: Optional[str] = None
    username: Optional[str] = None


class ShmSegment(BaseModel):
    """Represents a System V Shared Memory Segment."""
    id: int = Field(..., description="Shared memory ID (shmid)")
    key: str = Field(..., description="Numeric or hex IPC Key")
    owner: str = Field(..., description="Owner username or UID")
    perms: str = Field(..., description="Permission string or octal representation")
    bytes: int = Field(default=0, description="Size in bytes (SEGSZ)")
    nattch: int = Field(default=0, description="Current attached processes count")
    status: str = Field(default="", description="Status flags (e.g. 'dest' or empty)")
    cpid: Optional[int] = Field(default=None, description="Creator PID")
    lpid: Optional[int] = Field(default=None, description="Last operator PID")
    atime: Optional[str] = Field(default=None, description="Last attach time")
    dtime: Optional[str] = Field(default=None, description="Last detach time")
    ctime: Optional[str] = Field(default=None, description="Last change time")
    creator_process: Optional[ProcessInfo] = None
    last_process: Optional[ProcessInfo] = None
    is_abandoned: bool = False
    leak_confidence: LeakConfidence = LeakConfidence.NONE
    leak_reasons: List[str] = Field(default_factory=list)

    @property
    def bytes_human(self) -> str:
        return format_bytes_human(self.bytes)


class MessageQueue(BaseModel):
    """Represents a System V Message Queue."""
    id: int = Field(..., description="Message Queue ID (msqid)")
    key: str = Field(..., description="Numeric or hex IPC Key")
    owner: str = Field(..., description="Owner username or UID")
    perms: str = Field(..., description="Permission string or octal representation")
    used_bytes: int = Field(default=0, description="Current bytes buffered in queue")
    messages: int = Field(default=0, description="Number of messages in queue (qnum)")
    qbytes: Optional[int] = Field(default=None, description="Max allowed queue size in bytes")
    lspid: Optional[int] = Field(default=None, description="Last sender PID")
    lrpid: Optional[int] = Field(default=None, description="Last receiver PID")
    cpid: Optional[int] = Field(default=None, description="Creator PID")
    creator_process: Optional[ProcessInfo] = None
    is_abandoned: bool = False
    leak_confidence: LeakConfidence = LeakConfidence.NONE
    leak_reasons: List[str] = Field(default_factory=list)

    @property
    def used_bytes_human(self) -> str:
        return format_bytes_human(self.used_bytes)


class SemaphoreSet(BaseModel):
    """Represents a System V Semaphore Set."""
    id: int = Field(..., description="Semaphore Set ID (semid)")
    key: str = Field(..., description="Numeric or hex IPC Key")
    owner: str = Field(..., description="Owner username or UID")
    perms: str = Field(..., description="Permission string or octal representation")
    nsems: int = Field(default=1, description="Number of semaphores in set")
    cpid: Optional[int] = Field(default=None, description="Creator PID")
    creator_process: Optional[ProcessInfo] = None
    is_abandoned: bool = False
    leak_confidence: LeakConfidence = LeakConfidence.NONE
    leak_reasons: List[str] = Field(default_factory=list)


class AuditReport(BaseModel):
    """Comprehensive leak audit report generated by the IPC Cleaner Agent."""
    timestamp: str
    total_shm_count: int = 0
    total_shm_bytes: int = 0
    total_msg_count: int = 0
    total_sem_count: int = 0
    abandoned_shm_count: int = 0
    abandoned_shm_bytes: int = 0
    abandoned_msg_count: int = 0
    abandoned_sem_count: int = 0
    abandoned_shm: List[ShmSegment] = Field(default_factory=list)
    abandoned_msg: List[MessageQueue] = Field(default_factory=list)
    abandoned_sem: List[SemaphoreSet] = Field(default_factory=list)
    reclaimable_ram_bytes: int = 0
    reclaimable_ram_human: str = "0 B"
    all_shm: List[ShmSegment] = Field(default_factory=list)
    all_msg: List[MessageQueue] = Field(default_factory=list)
    all_sem: List[SemaphoreSet] = Field(default_factory=list)


class PurgeResult(BaseModel):
    """Result of purging IPC resources."""
    resource_type: str
    requested_ids: List[int]
    purged_ids: List[int] = Field(default_factory=list)
    failed_ids: Dict[int, str] = Field(default_factory=dict)
    reclaimed_bytes: int = 0
    reclaimed_bytes_human: str = "0 B"
    dry_run: bool = False
    method_used: str = "ipcrm"
